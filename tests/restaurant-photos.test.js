import test from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import photos from '../data/restaurant-space-images.json' with { type: 'json' };
import { createApp } from '../src/app.js';
import { restaurantPhoto } from '../src/lib/restaurant-photos.js';
import { testDatabase } from './helpers.js';

test('39 distinct restaurant space photos retain sources and separate fictional venues', async () => {
  assert.equal(photos.length,39);
  assert.equal(new Set(photos.map(p=>p.id)).size,39);
  assert.equal(new Set(photos.map(p=>p.imagePath)).size,39);
  assert.equal(photos.filter(p=>p.isDemo).length,3);
  const {db,storage}=testDatabase();
  const fixture=storage.restaurant[0];
  Object.assign(fixture,photos[0]);
  const app=createApp({db});
  const home=await request(app).get('/').expect(200);
  assert.match(home.text,/Không gian quán/);
  assert.match(home.text,/Nguồn ảnh không gian/);
  assert.ok(home.headers['content-security-policy'].includes(new URL(photos[0].imagePath).origin));
  const detail=await request(app).get('/restaurants/1').expect(200);
  assert.ok(detail.text.includes(photos[0].sourceUrl));
  assert.equal(restaurantPhoto({...photos[0],imagePath:'https://example.com/changed.jpg'}).sourceUrl,null);
  assert.equal(restaurantPhoto(photos[38]).label,'Không gian minh họa · Demo');
});
test('dish sorting popup contains immediate SSR links, preserves filters and resets pagination',async()=>{
  const {db}=testDatabase();
  const response=await request(createApp({db})).get('/dishes?district=Qu%E1%BA%ADn%201&page=2').expect(200);
  assert.match(response.text,/<dialog id="dish-options"/);
  assert.match(response.text,/aria-controls="dish-options">Tất cả món ăn ↗/);
  assert.ok(response.text.indexOf('id="search"')<response.text.indexOf('<dialog'));
  const popup=response.text.match(/<dialog[\s\S]*?<\/dialog>/)[0];
  assert.doesNotMatch(popup,/<form|<input|<select|<details/);
  assert.doesNotMatch(response.text,/<label for="dish-search">Tìm món ăn<\/label>/);
  const options=[...response.text.matchAll(/class="dish-sort-option[^>]*href="([^"]+)"/g)].map(m=>m[1]);
  assert.equal(options.length,8);
  assert.ok(options.every(url=>url.includes('district=')&&!url.includes('page=2')));
  assert.ok(options.some(url=>url.includes('sort=restaurant')));
  assert.ok(options.some(url=>url.includes('sort=district')));
});
